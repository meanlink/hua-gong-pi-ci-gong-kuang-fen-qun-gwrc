from enum import Enum
class Role(str, Enum):
    admin = 'admin'
    analyst = 'analyst'
    viewer = 'viewer'
class JobStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
class PlanRunStatus(str, Enum):
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
    superseded = 'superseded'
class StepStatus(str, Enum):
    pending = 'pending'
    queued = 'queued'
    running = 'running'
    completed = 'completed'
    failed = 'failed'
    blocked = 'blocked'
    invalidated = 'invalidated'
